#!/usr/bin/env node
// scripts/generate-profanity-splits.js
// Writes src/lib/profanity/profanitySplits.json: each English single-word term
// written with one space inside it ("bi tch"), so the filter catches a word that
// a viewer splits to get past it. The speech model reads the two halves as one
// word, so a split is as audible as the word itself.
//
// A split is dropped when both halves are real words: "who re" is in
// "who re-entered", and "s hit" is in "let's hit". The word list only runs here,
// at authoring time. The bot and the tests read the committed JSON, so neither
// one needs a dictionary on disk. Dropped splits are recorded too, so that a
// reviewer sees them in the diff and the test can tell a new term from a stale
// file.
//
// Usage: node scripts/generate-profanity-splits.js [--words /usr/share/dict/words]
// Run it again after any change to the English list in profanityLists.json.

import { readFileSync, writeFileSync } from 'fs';
import { dirname, join } from 'path';
import { fileURLToPath } from 'url';

const __dirname = dirname(fileURLToPath(import.meta.url));
const LISTS_PATH = join(__dirname, '../src/lib/profanity/profanityLists.json');
const OUT_PATH = join(__dirname, '../src/lib/profanity/profanitySplits.json');

// Only these languages get splits. The rest are short core lists, and their
// languages need their own word list for the real-word test.
const LANGUAGES = ['English'];

// Shorter terms split into fragments that occur in normal chat ("a ss").
const MIN_TERM_LENGTH = 4;

// A lone letter counts as a word only where chat really writes one. On the left
// that includes the contraction endings: "let's hit" holds "s hit", and the
// apostrophe before the "s" is a word boundary for the filter.
const LONE_LETTER_WORDS_LEFT = new Set(['a', 'i', 's', 't', 'd', 'm']);
const LONE_LETTER_WORDS_RIGHT = new Set(['a', 'i']);

// Endings that the dictionary leaves out. /usr/share/dict/words has "hit" but
// not "hitting", and "it's hitting" holds "s hitting".
const SUFFIXES = ['ings', 'ing', 'ers', 'er', 'es', 'ed', 's', 'd', 'y', 'ly', 'less', 'ness'];

// Splits that the real-word test drops, kept on purpose. Both halves are in the
// dictionary, but as rare words that normal chat does not put side by side.
const FORCE_KEEP = new Set([
    'nig ger', 'nig gers', 'nig ga', 'nig gas',
    'wan ker',
    'bit ches', 'bit ching',
    'sh it', 'sh itty',
]);

function parseArgs(argv) {
    const args = { words: '/usr/share/dict/words' };
    for (let i = 0; i < argv.length; i++) {
        if (argv[i] === '--words') args.words = argv[++i];
    }
    return args;
}

function makeIsWord(words) {
    const known = w => words.has(w);
    return (fragment, side) => {
        if (fragment.length === 1) {
            return (side === 'left' ? LONE_LETTER_WORDS_LEFT : LONE_LETTER_WORDS_RIGHT).has(fragment);
        }
        if (known(fragment)) return true;
        for (const suffix of SUFFIXES) {
            if (fragment.length <= suffix.length + 1 || !fragment.endsWith(suffix)) continue;
            const stem = fragment.slice(0, -suffix.length);
            if (known(stem) || known(stem + 'e')) return true;
            // "hitting" -> "hitt" -> "hit"
            if (stem.length > 2 && stem.at(-1) === stem.at(-2) && known(stem.slice(0, -1))) return true;
        }
        return false;
    };
}

function sortedObject(obj) {
    return Object.fromEntries(Object.entries(obj).sort(([a], [b]) => a.localeCompare(b)));
}

function main() {
    const args = parseArgs(process.argv.slice(2));
    const words = new Set(
        readFileSync(args.words, 'utf8').split('\n').map(w => w.trim().toLowerCase()).filter(Boolean)
    );
    const isWord = makeIsWord(words);
    const lists = JSON.parse(readFileSync(LISTS_PATH, 'utf8'));

    const out = {
        _README: [
            'Generated by scripts/generate-profanity-splits.js. Do not edit by hand.',
            'Each key is an English term with one space inside it. The value is the term.',
            'The filter speaks the replacement of that term.',
            '"splits" are matched. "dropped" are not matched, because both halves are real',
            'words and the split occurs in normal chat ("who re", "s hit").',
            'Only terms of letters a-z with at least 4 letters get splits. A split with a half',
            'that is itself a term is left out: the filter already catches that half.',
            'Run the script again after any change to the English list.',
        ],
    };

    for (const language of LANGUAGES) {
        const terms = new Set(lists[language].entries.map(e => e.term));
        const splits = {};
        const dropped = {};
        for (const term of terms) {
            if (!/^[a-z]+$/.test(term) || term.length < MIN_TERM_LENGTH) continue;
            for (let i = 1; i < term.length; i++) {
                const left = term.slice(0, i);
                const right = term.slice(i);
                const split = `${left} ${right}`;
                if (terms.has(split) || terms.has(left) || terms.has(right)) continue;
                const keep = FORCE_KEEP.has(split) || !(isWord(left, 'left') && isWord(right, 'right'));
                (keep ? splits : dropped)[split] = term;
            }
        }
        out[language] = { splits: sortedObject(splits), dropped: sortedObject(dropped) };
        console.log(`${language}: ${Object.keys(splits).length} splits, ${Object.keys(dropped).length} dropped`);
    }

    writeFileSync(OUT_PATH, JSON.stringify(out, null, 2) + '\n');
    console.log(`Wrote ${OUT_PATH}`);
}

main();
